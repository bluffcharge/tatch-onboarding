// Generates src/lib/screenSources.ts — a map of operator route pathname →
// the screen component's source, so the canvas can offer a "download .jsx"
// of whatever screen is being viewed. Bundled as strings (no runtime fs), so
// it works on the static Vercel deploy. Runs on `prebuild` (and can be run
// by hand: `node scripts/gen-screen-sources.mjs`).

import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "src/components/operator");

// route pathname (no query) → screen component file
const MAP = {
  "/operator/signin": "SignInScreen.tsx",
  "/operator/account": "CreateAccountScreen.tsx",
  "/operator/account/profile": "CreateAccountProfileScreen.tsx",
  "/operator/plan": "ChoosePlanScreen.tsx",
  "/operator/team": "InviteTeamScreen.tsx",
  "/operator/payment": "PaymentScreen.tsx",
  "/operator/activating": "ActivatingScreen.tsx",
  "/operator/done": "AllSetScreen.tsx",
};

const out = {};
for (const [route, file] of Object.entries(MAP)) {
  out[route] = {
    file: file.replace(/\.tsx$/, ".jsx"),
    code: readFileSync(join(dir, file), "utf8"),
  };
}

const banner = "// AUTO-GENERATED by scripts/gen-screen-sources.mjs — do not edit by hand.\n";
const body =
  "export type ScreenSource = { file: string; code: string };\n" +
  `export const SCREEN_SOURCES: Record<string, ScreenSource> = ${JSON.stringify(out, null, 2)};\n`;

writeFileSync(join(root, "src/lib/screenSources.ts"), banner + body);
console.log(`Generated src/lib/screenSources.ts (${Object.keys(out).length} screens)`);
